'use strict';

const assert = require('node:assert/strict');
const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const test = require('node:test');
const { buildScaffoldDxf, buildScaffoldFreeCadMacro, buildScaffoldObj, buildScaffoldSvg } = require('../lib/scaffold-exports');

test('local HTTP API persists projects, rejects stale revisions and stores map markers', async (t) => {
  const directory=fs.mkdtempSync(path.join(os.tmpdir(),'teline-api-test-'));
  process.env.TELINEHALLINTA_SCAFFOLD_DB=path.join(directory,'projects.sqlite');
  process.env.TELINEHALLINTA_FILES_DIR=path.join(directory,'files');
  process.env.TELINEHALLINTA_CRM_DB=path.join(directory,'crm.sqlite');
  const app=require('../server');
  const server=app.listen(0,'127.0.0.1');
  await new Promise((resolve,reject)=>{server.once('listening',resolve);server.once('error',reject);});
  const base='http://127.0.0.1:'+server.address().port;
  t.after(async()=>{
    await new Promise((resolve)=>server.close(resolve));
    app.locals.closeScaffoldProjectStore();
    fs.rmSync(directory,{recursive:true,force:true});
    delete process.env.TELINEHALLINTA_SCAFFOLD_DB;
    delete process.env.TELINEHALLINTA_FILES_DIR;
    delete process.env.TELINEHALLINTA_CRM_DB;
  });
  async function request(url,method='GET',body){
    const response=await fetch(base+url,{method,headers:body?{'content-type':'application/json'}:{},body:body?JSON.stringify(body):undefined});
    return {status:response.status,json:response.status===204?null:await response.json()};
  }
  const nativeFetch=global.fetch;
  global.fetch=async(input,init)=>{
    const url=new URL(typeof input==='string'||input instanceof URL?input:input.url);
    if(url.hostname==='kartta.hel.fi'&&url.pathname==='/ws/geoserver/avoindata/wfs'){
      assert.equal(url.searchParams.get('typeNames'),'avoindata:Rakennukset_alue_rekisteritiedot');
      assert.equal(url.searchParams.get('srsName'),'EPSG:3879');
      return new Response(JSON.stringify({type:'FeatureCollection',features:[{type:'Feature',id:'Rakennukset.123',geometry:{type:'Polygon',coordinates:[[[25496800,6673000],[25496810,6673000],[25496810,6673010],[25496800,6673010],[25496800,6673000]]]},properties:{ratu:123,tyyppi:'Liikerakennus',katunimi_suomi:'Testikatu',osoitenumero:'1',i_kerrlkm:4}}]}),{status:200,headers:{'content-type':'application/json'}});
    }
    return nativeFetch(input,init);
  };
  let footprints;
  try{
    footprints=await request('/api/helsinki/building-footprints?x=25496825&y=6673044&radius=75&count=5');
    assert.equal(footprints.status,200);
    assert.equal(footprints.json.source,'Helsingin kaupungin rakennusten alue- ja rekisteritiedot');
    assert.equal(footprints.json.crs,'EPSG:3879');
    assert.equal(footprints.json.data.features[0].properties.ratu,123);
    assert.equal(footprints.json.data.features[0].geometry.type,'Polygon');
  }finally{global.fetch=nativeFetch;}
  const company=(await request('/api/crm/companies','POST',{name:'Testiasiakas Oy'})).json.company;
  const body={name:'API-testiteline',customerId:company.id,customerName:'Väärennetty nimi',building:{name:'Testikohde',source:'Käsin syötetty',projectCrs:'EPSG:3879',height:{value:8,status:'user',source:'Käyttäjä'}},geometry:{targetLengthM:12,targetHeightM:8,buildingDepthM:6,platformLevels:[2],scale:100},pricing:{components:{},catalogLinks:{'base-jack':{catalogId:'HAKI|HAKI Universal|CAT-BASE',manufacturer:'HAKI',system:'HAKI Universal',itemNo:'CAT-BASE',name:'Valittu tukijalka',size:'testikoko',source:'https://example.test/catalog/base',revision:'Katalogi 2026'}},labor:[{description:'Asennus',hours:10,ratePerHour:50,source:'Käyttäjän hintasyöte'}],transport:[],otherCosts:0}};
  const sourceFeature=footprints.json.data.features[0], sourceRing=sourceFeature.geometry.coordinates[0];
  const importedBuilding=await request('/api/scaffold/projects','POST',{...body,name:'Testikatu 1 · teline',building:{id:sourceFeature.id,name:sourceFeature.properties.tyyppi,address:'Testikatu 1',parcelId:'091-001-0001-0001',source:footprints.json.source,sourceCrs:'EPSG:3879',projectCrs:'EPSG:3879',retrievedAt:'2026-10-28T08:00:00.000Z',footprint:sourceRing,footprintStatus:'source',facadeIndex:0,height:{value:12,status:'estimate',source:'Helsingin rekisteri · 4 kerrosta × 3 m (arvio)'},properties:sourceFeature.properties}});
  assert.equal(importedBuilding.status,201);
  assert.equal(importedBuilding.json.building.address,'Testikatu 1');
  assert.equal(importedBuilding.json.building.sourceCrs,'EPSG:3879');
  assert.deepEqual(importedBuilding.json.building.footprint,sourceRing);
  assert.equal(importedBuilding.json.building.properties.ratu,123);
  assert.equal(importedBuilding.json.building.height.status,'estimate');
  assert.equal(importedBuilding.json.provenance.targetLength.status,'source');
  const created=await request('/api/scaffold/projects','POST',body);
  assert.equal(created.status,201);
  assert.equal(created.json.revision,1);
  assert.equal(created.json.customerId,company.id);
  assert.equal(created.json.customerName,'Testiasiakas Oy');
  assert.equal(created.json.model.dimensions.bays,3);
  assert.equal(created.json.model.bom.find((line)=>line.id==='base-jack').catalogLink.itemNo,'CAT-BASE');
  assert.equal(created.json.model.bom.find((line)=>line.id==='base-jack').catalogLink.status,'user-selected-needs-compatibility-review');
  const unchanged=await request('/api/scaffold/projects/'+created.json.id,'PUT',{...body,expectedRevision:1});
  assert.equal(unchanged.status,200);
  assert.equal(unchanged.json.revision,1);
  assert.equal((await request('/api/scaffold/projects/'+created.json.id+'/revisions')).json.revisions.length,1);
  const pipeline=await request('/api/scaffold/projects/'+created.json.id+'/pipeline','POST',{});
  assert.equal(pipeline.status,201);
  assert.equal(pipeline.json.opportunity.company_id,company.id);
  assert.equal(pipeline.json.opportunity.stage,'Tarjousvalmistelu');
  assert.equal(pipeline.json.opportunity.value,0,'CRM opportunity must not present a cost subtotal as a complete quote value');
  assert.match(pipeline.json.opportunity.review_note,/Kateprosentti puuttuu/);
  assert.match(pipeline.json.opportunity.review_note,/ALV-prosentti puuttuu/);
  assert.equal(pipeline.json.opportunity.source_id,created.json.id);
  assert.match(pipeline.json.opportunity.source_url,/projectId=/);
  const deliveryInput={date:'2026-11-02',time:'08:30',vehicle:'Kuorma-auto · TESTI',expectedRevision:1};
  const delivery=await request('/api/scaffold/projects/'+created.json.id+'/deliveries','POST',deliveryInput);
  assert.equal(delivery.status,201);
  assert.equal(delivery.json.delivery.projectRevision,1);
  assert.equal(delivery.json.delivery.status,'Suunniteltu');
  assert.equal(delivery.json.delivery.items.length,created.json.model.bom.length);
  assert.equal(delivery.json.delivery.totalQuantity,created.json.model.bom.reduce((sum,line)=>sum+line.quantity,0));
  const linkedDeliveryItem=delivery.json.delivery.items.find((item)=>item.modelItemNo==='2071000');
  assert.equal(linkedDeliveryItem.itemNo,'CAT-BASE');
  assert.equal(linkedDeliveryItem.modelItemNo,'2071000');
  assert.equal(linkedDeliveryItem.catalogLinkStatus,'user-selected-needs-compatibility-review');
  assert.equal((await request('/api/scaffold/projects/'+created.json.id+'/deliveries','POST',deliveryInput)).json.duplicate,true);
  const secondDelivery=await request('/api/scaffold/projects/'+created.json.id+'/deliveries','POST',{date:'2026-11-03',time:'10:00',vehicle:'Kuorma-auto · TESTI',expectedRevision:1});
  assert.equal(secondDelivery.status,201);
  assert.equal(secondDelivery.json.duplicate,false);
  assert.equal(secondDelivery.json.delivery.projectRevision,1);
  assert.equal(secondDelivery.json.delivery.totalQuantity,delivery.json.delivery.totalQuantity);
  const deliveryStatus=await request('/api/scaffold/deliveries/'+delivery.json.delivery.id,'PATCH',{status:'Lastaus'});
  assert.equal(deliveryStatus.json.delivery.status,'Lastaus');
  const updated=await request('/api/scaffold/projects/'+created.json.id,'PUT',{...body,name:'API-testiteline 2',expectedRevision:1});
  assert.equal(updated.status,200);
  assert.equal(updated.json.revision,2);
  const staleDelivery=await request('/api/scaffold/projects/'+created.json.id+'/deliveries','POST',{...deliveryInput,date:'2026-11-04'});
  assert.equal(staleDelivery.status,409);
  assert.equal(staleDelivery.json.currentRevision,2);
  const refreshedPipeline=await request('/api/scaffold/projects/'+created.json.id+'/pipeline','POST',{});
  assert.equal(refreshedPipeline.status,200);
  assert.equal(refreshedPipeline.json.duplicate,true);
  assert.equal(refreshedPipeline.json.opportunity.id,pipeline.json.opportunity.id);
  assert.equal(refreshedPipeline.json.trackedRevision,2);
  const activities=await request('/api/crm/opportunities/'+pipeline.json.opportunity.id+'/activities');
  const projectUpdates=activities.json.filter((item)=>item.kind==='telineprojekti');
  assert.equal(projectUpdates.length,2);
  assert.match(projectUpdates[0].summary,/rev 2/);
  assert.match(projectUpdates[1].summary,/rev 1/);
  assert.match(projectUpdates[0].source_url,/projectId=/);
  const conflict=await request('/api/scaffold/projects/'+created.json.id,'PUT',{...body,expectedRevision:1});
  assert.equal(conflict.status,409);
  const reviewed=await request('/api/scaffold/projects/'+created.json.id+'/review','POST',{expectedRevision:2,reviewer:'Testaaja',decision:'reviewed',note:'Hyväksyntäpolun smoke test'});
  assert.equal(reviewed.status,200);
  assert.equal(reviewed.json.revision,3);
  assert.equal(reviewed.json.workflow.state,'reviewed');
  const reviewedNoop=await request('/api/scaffold/projects/'+created.json.id,'PUT',{...body,name:'API-testiteline 2',expectedRevision:3});
  assert.equal(reviewedNoop.status,200);
  assert.equal(reviewedNoop.json.revision,3);
  assert.equal(reviewedNoop.json.workflow.state,'reviewed');
  const revisions=await request('/api/scaffold/projects/'+created.json.id+'/revisions');
  assert.deepEqual(revisions.json.revisions.map((row)=>row.revision),[3,2,1]);
  const upload=await fetch(base+'/api/scaffold/projects/'+created.json.id+'/files',{method:'POST',headers:{'content-type':'application/octet-stream','x-file-name':encodeURIComponent('../julkisivu.pdf'),'x-file-kind':'drawing'},body:Buffer.from('%PDF-test')});
  assert.equal(upload.status,201);
  const file=await upload.json();
  assert.equal(file.filename,'julkisivu.pdf');
  assert.equal(file.revision,3);
  assert.equal('contents' in file,false);
  const files=await request('/api/scaffold/projects/'+created.json.id+'/files');
  assert.equal(files.json.files.length,1);
  const downloaded=await fetch(base+file.downloadUrl);
  assert.equal(downloaded.status,200);
  assert.equal(await downloaded.text(),'%PDF-test');
  for(const [extension,contents,kind] of [['dxf',buildScaffoldDxf(reviewed.json),'drawing'],['svg',buildScaffoldSvg(reviewed.json),'drawing'],['obj',buildScaffoldObj(reviewed.json),'scaffold-model'],['FCMacro',buildScaffoldFreeCadMacro(reviewed.json),'scaffold-model'],['csv','\ufeff"TelineHallinta BOM";""\r\n','other']]){
    const cadUpload=await fetch(base+'/api/scaffold/projects/'+created.json.id+'/files',{method:'POST',headers:{'content-type':'application/octet-stream','x-file-name':'API-'+extension+'.'+extension,'x-file-kind':kind},body:contents});
    assert.equal(cadUpload.status,201);
    const cadFile=await cadUpload.json();
    assert.equal(cadFile.revision,3);
    const cadDownload=await fetch(base+cadFile.downloadUrl);
    if(extension==='FCMacro') assert.match(cadDownload.headers.get('content-type'),/text\/x-python/);
    assert.equal(await cadDownload.text(),contents.replace(/^\uFEFF/,''));
  }
  assert.equal((await fetch(base+'/api/scaffold/projects/'+created.json.id+'/files',{method:'POST',headers:{'content-type':'application/octet-stream','x-file-name':'bad.exe','x-file-kind':'drawing'},body:Buffer.from('x')})).status,415);
  const template=await request('/api/scaffold/projects/'+created.json.id+'/templates','POST',{name:'API-telinemalli'});
  assert.equal(template.status,201);
  assert.equal(template.json.template.geometry.targetLengthM,12);
  assert.equal((await request('/api/scaffold/templates')).json.templates.length,1);
  app.locals.closeScaffoldProjectStore();
  const reopenedBuilding=await request('/api/scaffold/projects/'+importedBuilding.json.id);
  assert.equal(reopenedBuilding.status,200);
  assert.equal(reopenedBuilding.json.building.name,'Liikerakennus');
  assert.equal(reopenedBuilding.json.building.address,'Testikatu 1');
  assert.deepEqual(reopenedBuilding.json.building.footprint,sourceRing);
  assert.equal(reopenedBuilding.json.building.properties.ratu,123);
  assert.equal(reopenedBuilding.json.building.height.status,'estimate');
  assert.equal((await request('/api/scaffold/projects/'+created.json.id+'/files')).json.files.length,6);
  const savedDeliveries=(await request('/api/scaffold/deliveries')).json.deliveries;
  assert.equal(savedDeliveries.length,2);
  assert.equal(savedDeliveries.find((item)=>item.id===delivery.json.delivery.id).status,'Lastaus');
  assert.equal(await (await fetch(base+file.downloadUrl)).text(),'%PDF-test');
  assert.equal((await request('/api/scaffold/templates/'+template.json.id)).json.template.geometry.targetLengthM,12);
  const marker=await request('/api/geo/management-markers','POST',{moduleKey:'scaffold',title:'API-karttamerkki',easting:25496580.36,northing:6673003.61,crs:'EPSG:3879'});
  assert.equal(marker.status,201);
  const markers=await request('/api/geo/management-markers');
  assert.equal(markers.json.crs,'EPSG:3879');
  assert.equal(markers.json.markers[0].id,marker.json.id);
  const removed=await request('/api/geo/management-markers/'+marker.json.id,'DELETE');
  assert.equal(removed.status,204);
});
